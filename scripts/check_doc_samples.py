"""Keep the output samples embedded in the docs identical to the golden files.

Every output sample in ``docs/output-formats.md`` must be generated by the real
code, never written by hand (milestone 0009, Story 03.0, Task 03, decision
D3). The golden files ``tests/data/output_formats/sample.<ext>`` are produced
from a synthetic fixture by ``tests/unit/doc_samples_test.cpp``; this script
checks (or re-syncs) the copies embedded in the docs.

Marker syntax: an HTML comment on its own line, immediately followed by a
fenced code block (the fence may carry an info string such as ``json``)::

    <!-- sample: tests/data/output_formats/sample.json -->
    ```json
    ...file contents, verbatim...
    ```

The path is relative to the repository root and must stay inside it. The
block body (everything between the opening and closing fence lines) must
equal the file byte-for-byte; a file that does not end with a newline is
compared as if it did, since a closing fence always starts on its own line.

Modes:

- ``--check`` (default): exit ``1`` on any drifted block, a marker not
  immediately followed by a fenced block, or a missing referenced file.
- ``--write``: rewrite every marked block from its file (fixing drift), then
  exit ``1`` only if a marker is malformed or a referenced file is missing.

A document that does not exist yet, or contains no markers, has nothing to
check: the script says so and exits ``0``.

Usage::

    python3 scripts/check_doc_samples.py --check
    python3 scripts/check_doc_samples.py --write
    python3 scripts/check_doc_samples.py --check --doc docs/output-formats.md

Standard library only. Prints file and line numbers, never sample content.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DOC = "docs/output-formats.md"

MARKER_RE = re.compile(r"^\s*<!--\s*sample:\s*(?P<path>\S+)\s*-->\s*$")
FENCE_RE = re.compile(r"^(?P<fence>`{3,}|~{3,})(?P<info>[^`]*)$")


class SampleError(Exception):
    """A malformed marker or a missing/unsafe referenced file."""


def strip_eol(line: str) -> str:
    """Return ``line`` without its trailing LF or CRLF."""
    return line.rstrip("\r\n")


def resolve_sample(rel_path: str) -> Path:
    """Resolve a marker path against the repo root, refusing escapes."""
    candidate = (REPO_ROOT / rel_path).resolve()
    if REPO_ROOT not in candidate.parents:
        raise SampleError(f"sample path '{rel_path}' leaves the repository")
    if not candidate.is_file():
        raise SampleError(f"referenced sample file '{rel_path}' does not exist")
    return candidate


def expected_body(sample: Path) -> str:
    """The exact block body the sample file requires."""
    text = sample.read_bytes().decode("utf-8")
    return text if text.endswith("\n") or not text else text + "\n"


def fence_for(body: str, original: str) -> str:
    """A fence longer than any backtick run inside ``body`` (keeps ``original`` if safe)."""
    longest = max((len(run) for run in re.findall(r"`+", body)), default=0)
    if original.startswith("`") and len(original) > longest:
        return original
    return "`" * max(3, longest + 1)


def process(doc: Path, write: bool) -> int:
    """Check (or rewrite) every marked block in ``doc``; return the problem count."""
    lines = doc.read_bytes().decode("utf-8").splitlines(keepends=True)
    rel_doc = doc.relative_to(REPO_ROOT) if REPO_ROOT in doc.parents else doc
    output: list[str] = []
    problems = 0
    markers = 0
    index = 0

    while index < len(lines):
        line = lines[index]
        output.append(line)
        index += 1
        marker = MARKER_RE.match(strip_eol(line))
        if not marker:
            continue
        markers += 1
        marker_line = index
        try:
            sample = resolve_sample(marker.group("path"))
            if index >= len(lines):
                raise SampleError("marker is not followed by a fenced block")
            opening = FENCE_RE.match(strip_eol(lines[index]))
            if not opening:
                raise SampleError("marker is not immediately followed by a fenced block")
            fence = opening.group("fence")
            close = index + 1
            while close < len(lines) and strip_eol(lines[close]).strip() != fence:
                close += 1
            if close >= len(lines):
                raise SampleError("fenced block after marker is never closed")
        except SampleError as error:
            print(f"{rel_doc}:{marker_line}: {error}", file=sys.stderr)
            problems += 1
            continue

        body = "".join(lines[index + 1:close]).replace("\r\n", "\n")
        wanted = expected_body(sample)
        if write:
            new_fence = fence_for(wanted, fence)
            output.append(f"{new_fence}{opening.group('info')}\n")
            output.append(wanted)
            output.append(f"{new_fence}\n")
            if body != wanted:
                print(f"{rel_doc}:{marker_line}: re-synced from {marker.group('path')}")
        else:
            output.extend(lines[index:close + 1])
            if body != wanted:
                print(f"{rel_doc}:{marker_line}: block differs from {marker.group('path')}",
                      file=sys.stderr)
                problems += 1
        index = close + 1

    if markers == 0:
        print(f"{rel_doc}: no sample markers, nothing to check")
    if write and problems == 0:
        new_text = "".join(output)
        if new_text.encode("utf-8") != doc.read_bytes():
            doc.write_bytes(new_text.encode("utf-8"))
    return problems


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="verify only (default)")
    mode.add_argument("--write", action="store_true", help="re-sync blocks from the sample files")
    parser.add_argument("--doc", action="append", default=None,
                        help=f"document to process, relative to the repo root (default: {DEFAULT_DOC})")
    args = parser.parse_args(argv)

    problems = 0
    for rel_doc in args.doc or [DEFAULT_DOC]:
        doc = (REPO_ROOT / rel_doc).resolve()
        if not doc.is_file():
            print(f"{rel_doc}: does not exist yet, nothing to check")
            continue
        problems += process(doc, write=args.write)

    if problems:
        print(f"check_doc_samples: {problems} problem(s)", file=sys.stderr)
        return 1
    print("check_doc_samples: ok")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
